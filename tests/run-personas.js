#!/usr/bin/env node
// Runs every test visitor in personas.json through the inference engine in
// index.html and writes results.md. The engine code is read straight from the
// page (between the INFERENCE ENGINE START/END markers), so tests always run
// exactly what the page runs.
//
// Usage: node tests/run-personas.js
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const start = html.indexOf('// ══ INFERENCE ENGINE START ══');
const end = html.indexOf('// ══ INFERENCE ENGINE END ══');
if (start < 0 || end < 0) { console.error('Engine markers not found in index.html'); process.exit(1); }
const engine = new Function(html.slice(start, end) + '\nreturn { inferProfile, inferLive };')();

const { base, personas } = JSON.parse(fs.readFileSync(path.join(__dirname, 'personas.json'), 'utf8'));
// Area data (Z), loaded from data/ the way the page loads it: only for US connections (devlog 041).
const readData = f => JSON.parse(fs.readFileSync(path.join(root, 'data', f), 'utf8'));
const Z = { gpc: readData('gpc-states.json'), income: readData('zip-income-housing.json'), language: readData('zip-language.json'),
            industry: readData('zip-industry.json'), earnings: readData('zip-industry-earnings.json') };
const isObj = v => v && typeof v === 'object' && !Array.isArray(v);
function merge(a, b) {
  const out = Array.isArray(a) ? a.slice() : Object.assign({}, a);
  for (const k of Object.keys(b || {})) out[k] = isObj(a && a[k]) && isObj(b[k]) ? merge(a[k], b[k]) : b[k];
  return out;
}

const ruleCounts = {};
const lines = [];
const results = personas.map(p => {
  const D = merge(base, p.data);
  if (D.N && D.N.status === 'ok' && D.N.country === 'US') D.Z = Z;
  const r = engine.inferProfile(D);
  const live = engine.inferLive(D.B);
  // A conclusion that fired but was suppressed (e.g. a contradiction) still counts as fired.
  const ids = new Set([...r.fired, ...r.conclusions, ...live.ids, ...r.suppressed.filter(s => s.id.startsWith('T2-')).map(s => s.id)]);
  ids.forEach(id => { ruleCounts[id] = (ruleCounts[id] || 0) + 1; });
  const conflict = r.suppressed.some(s => s.reason.startsWith('contradicts'));
  const missed = (p.targets || []).filter(t => t === 'conflict' ? !conflict : !ids.has(t));
  return { p, r, live, missed };
});

lines.push('# Persona test results', '');
lines.push(`Generated by \`node tests/run-personas.js\` against the engine in \`index.html\`. ${personas.length} test visitors.`, '');
lines.push('**Reading this:** each visitor shows the profile text exactly as the page would render it, then which rules fired, which conclusions fired, and anything suppressed by the assembly step. "Targets" are the rules the visitor was designed to trigger; any that didn\'t fire are listed as missed.', '');

lines.push('## Coverage', '');
// T1-14 and T1-26 removed (devlogs 028, 037); T2-K dropped (devlog 037)
const allIds = ['T1-01','T1-02','T1-03','T1-04','T1-05','T1-06','T1-07','T1-08','T1-09','T1-10','T1-11','T1-12','T1-13','T1-15','T1-16','T1-17','T1-18','T1-19','T1-20','T1-21','T1-22','T1-23','T1-24','T1-25','T1-27','T1-28','T1-29','T1-30','T1-31','T1-32','T1-33','T1-34','T1-35','T1-36','T1-37',
  'T2-A','T2-B','T2-C','T2-D','T2-E','T2-F','T2-G','T2-H','T2-I','T2-J','T2-L','T2-M','T2-N','T2-O'];
lines.push('| Rule | Visitors that fired it |', '|---|---|');
allIds.forEach(id => lines.push(`| ${id} | ${ruleCounts[id] || '**0**'} |`));
const never = allIds.filter(id => !ruleCounts[id]);
lines.push('', never.length ? `**Never fired:** ${never.join(', ')}` : '**Every rule fired at least once.**', '');
const misses = results.filter(x => x.missed.length);
lines.push(misses.length ? `**Missed targets:** ${misses.map(x => `${x.p.id} (${x.missed.join(', ')})`).join('; ')}` : '**All targets hit.**', '');

lines.push('---', '');
results.forEach(({ p, r, live, missed }) => {
  lines.push(`## ${p.id} · ${p.name}`, '');
  r.paragraphs.forEach(par => lines.push(`> ${par.text}`, '>'));
  if (live.text) lines.push(`> ${live.text}`, '>');
  if (lines[lines.length - 1] === '>') lines.pop();
  lines.push('');
  lines.push(`- **Rules fired:** ${r.fired.join(', ') || 'none'}${live.ids.length ? ', T1-27 (live)' : ''}`);
  lines.push(`- **Conclusions:** ${r.conclusions.join(', ') || 'none'}`);
  if (r.suppressed.length) lines.push(`- **Suppressed:** ${r.suppressed.map(s => `${s.id} (${s.reason})`).join('; ')}`);
  lines.push(`- **Targets:** ${(p.targets || []).join(', ')}${missed.length ? ` · **missed: ${missed.join(', ')}**` : ' · all hit'}`);
  lines.push(`- **Summary row time zone:** ${r.zoneName}`);
  lines.push('');
});

fs.writeFileSync(path.join(__dirname, 'results.md'), lines.join('\n'));
console.log(`Wrote tests/results.md (${personas.length} visitors).`);
console.log(never.length ? `Never fired: ${never.join(', ')}` : 'Every rule fired at least once.');
console.log(misses.length ? `Missed targets: ${misses.map(x => `${x.p.id} (${x.missed.join(', ')})`).join('; ')}` : 'All targets hit.');
